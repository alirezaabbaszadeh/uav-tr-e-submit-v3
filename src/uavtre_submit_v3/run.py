def _write_exec_manifest(*, campaign_id: str, out_submission_dir: Path, out_manuscript_dir: Path) -> Path:
    manifest_path = out_submission_dir / f"MANUSCRIPT_EXEC_MANIFEST_{campaign_id}.json"

    artifacts: list[Path] = [
        out_manuscript_dir / "camera_ready" / "main.pdf",
        out_manuscript_dir / "anonymous" / "main.pdf",
        out_submission_dir / f"TR_E_UPLOAD_CHECKLIST_{campaign_id}.md",
        out_submission_dir / f"CLAIM_EVIDENCE_MAP_{campaign_id}.md",
        out_submission_dir / f"TABLE_FIGURE_INDEX_{campaign_id}.md",
        out_submission_dir / "proposal_highlights.txt",
        out_submission_dir / "cover_letter.txt",
        out_submission_dir / "TR_E_METADATA.yaml",
    ]

    items = []
    for p in artifacts:
        if not p.exists():
            continue
        items.append({"path": p.as_posix(), "bytes": p.stat().st_size, "sha256": _sha256(p)})

    payload = {
        "generated_at_utc": _utc_now(),
        "campaign_id": campaign_id,
        "artifacts": items,
    }
    manifest_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return manifest_path


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="submit_v3: evidence-locked TR-E manuscript pipeline (no rerun)")
    p.add_argument("--campaign-id", required=True)
    p.add_argument("--evidence-root", required=True, help="path to outputs/campaigns or the campaign dir")
    p.add_argument("--audit-json", required=True)
    p.add_argument("--mode", choices=["full"], default="full")
    p.add_argument("--pdf-variant", choices=["camera_ready", "anonymous"], default="camera_ready")
    p.add_argument("--resume", action="store_true")

    args = p.parse_args(argv)

    repo_root = Path(__file__).resolve().parents[2]
    evidence_root = Path(args.evidence_root).expanduser().resolve()
    audit_json = Path(args.audit_json).expanduser().resolve()

    campaign_dir = _resolve_campaign_dir(evidence_root, args.campaign_id)
    if not campaign_dir.exists():
        raise FileNotFoundError(campaign_dir)

    manuscript_root = repo_root / "manuscript" / "tr_e"
    out_submission_dir = repo_root / "out" / "submission"
    out_manuscript_dir = repo_root / "out" / "manuscript"

    out_submission_dir.mkdir(parents=True, exist_ok=True)
    (out_manuscript_dir / "camera_ready").mkdir(parents=True, exist_ok=True)
    (out_manuscript_dir / "anonymous").mkdir(parents=True, exist_ok=True)

    # S01: evidence lock.
    evidence_lock_json = out_submission_dir / f"EVIDENCE_LOCK_REPORT_{args.campaign_id}.json"
    lock_res = lock_evidence(campaign_dir=campaign_dir, out_json=evidence_lock_json)
    if not lock_res.passed:
        raise RuntimeError(f"evidence lock failed (missing: {lock_res.missing_files})")

    # S02: audit recheck.
    audit_recheck_json = out_submission_dir / f"AUDIT_RECHECK_{args.campaign_id}.json"
    _audit_recheck(audit_json=audit_json, out_path=audit_recheck_json)

    # S03: generate assets.
    base_cfg = repo_root / "configs" / "base.json"
    generate_assets(campaign_dir=campaign_dir, manuscript_root=manuscript_root, base_config_path=base_cfg)

    # S04: campaign lock snippet for manuscript.
    _write_campaign_lock(
        campaign_id=args.campaign_id,
        campaign_dir=campaign_dir,
        out_path=manuscript_root / "generated" / "campaign_lock.tex",
    )

    # S05: compile PDFs.
    compile_manuscript(
        repo_root=repo_root,
        manuscript_root=manuscript_root,
        outdir=out_manuscript_dir / "camera_ready",
        variant="camera_ready",
    )
    compile_manuscript(
        repo_root=repo_root,
        manuscript_root=manuscript_root,
        outdir=out_manuscript_dir / "anonymous",
        variant="anonymous",
    )

    # S06: submission artifacts.
    _ensure_metadata_template(out_submission_dir)
    _write_submission_texts(campaign_id=args.campaign_id, out_submission_dir=out_submission_dir)

    # Materialize metadata now (strict: no TODO_).
    # build_tr_e_upload_pack will also enforce this.
    from .pack_builder import materialize_metadata

    materialize_metadata(
        out_submission_dir / "TR_E_METADATA_TEMPLATE.yaml",
        out_submission_dir / "TR_E_METADATA.yaml",
    )

    # Exec manifest for pack.
    exec_manifest = _write_exec_manifest(
        campaign_id=args.campaign_id,
        out_submission_dir=out_submission_dir,
        out_manuscript_dir=out_manuscript_dir,
    )

    # S07: build upload pack.
    pack = build_tr_e_upload_pack(
        campaign_id=args.campaign_id,
        out_submission_dir=out_submission_dir,
        out_manuscript_dir=out_manuscript_dir,
        manuscript_root=manuscript_root,
        audit_recheck_json=audit_recheck_json,
        manifest_json=exec_manifest,
        pdf_variant=args.pdf_variant,
    )

    # S08: QA.
    _, qa_report = run_qa(
        campaign_id=args.campaign_id,
        out_submission_dir=out_submission_dir,
        out_manuscript_dir=out_manuscript_dir,
        manuscript_root=manuscript_root,
        audit_recheck_json=audit_recheck_json,
        evidence_lock_json=evidence_lock_json,
    )

    qa_path = out_submission_dir / f"FINAL_QA_REPORT_{args.campaign_id}.json"
    qa_path.write_text(json.dumps(qa_report, indent=2), encoding="utf-8")
    if not qa_report.get("passed", False):
        raise RuntimeError(f"final QA failed: {qa_report.get('checks')}")

    # Print a compact run summary for the CLI.
    summary = {
        "campaign_id": args.campaign_id,
        "campaign_dir": campaign_dir.as_posix(),
        "out_manuscript": out_manuscript_dir.as_posix(),
        "out_submission": out_submission_dir.as_posix(),
        "pack": pack.as_posix(),
        "qa": qa_path.as_posix(),
    }
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
