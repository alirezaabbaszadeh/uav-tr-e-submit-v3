def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            chunk = f.read(1024 * 1024)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def _resolve_campaign_dir(evidence_root: Path, campaign_id: str) -> Path:
    if evidence_root.name == campaign_id and evidence_root.exists():
        return evidence_root
    return evidence_root / campaign_id


def _audit_recheck(*, audit_json: Path, out_path: Path) -> None:
    if not audit_json.exists():
        raise FileNotFoundError(audit_json)
    payload = json.loads(audit_json.read_text(encoding="utf-8"))
    summary = payload.get("summary", {})
    if not bool(summary.get("overall_pass", False)):
        raise RuntimeError(f"audit overall_pass is false: {audit_json}")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def _write_campaign_lock(*, campaign_id: str, campaign_dir: Path, out_path: Path) -> None:
    manifest_path = campaign_dir / "CAMPAIGN_MANIFEST.json"
    manifest = {}
    if manifest_path.exists():
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception:
            manifest = {}

    git_sha = str(manifest.get("git_sha", ""))
    env_hash = str(manifest.get("env_hash", ""))

    tex = (
        "% Auto-generated by submit_v3. Do not edit by hand.\n"
        f"\\newcommand{{\\CampaignID}}{{{campaign_id.replace('_', '\\_')}}}\n"
        f"\\newcommand{{\\CampaignGitSHA}}{{{git_sha.replace('_', '\\_')}}}\n"
        f"\\newcommand{{\\CampaignEnvHash}}{{{env_hash.replace('_', '\\_')}}}\n"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(tex, encoding="utf-8")


